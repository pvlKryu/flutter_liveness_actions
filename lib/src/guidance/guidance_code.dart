/// guidance code.
enum GuidanceCode {
  /// move closer.
  moveCloser,

  /// move farther.
  moveFarther,

  /// center face.
  centerFace,

  /// improve lighting.
  improveLighting,

  /// hold still.
  holdStill,

  /// blink once.
  blinkOnce,

  /// turn head left.
  turnHeadLeft,

  /// turn head right.
  turnHeadRight,

  /// only one person.
  onlyOnePerson,

  /// camera permission required.
  cameraPermissionRequired,

  /// challenge completed.
  challengeCompleted,

  /// retry challenge.
  retryChallenge,

  /// processing slow.
  processingSlow,

  /// face out of frame.
  faceOutOfFrame,

  /// no face detected.
  noFaceDetected,
}
